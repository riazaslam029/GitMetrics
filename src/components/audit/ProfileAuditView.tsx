import { useState, useMemo } from 'react';
import {
  CheckCircle2,
  Lightbulb,
  ExternalLink,
  Copy,
  Check,
  ShieldCheck,
  BookOpen,
  Tag,
  Globe,
} from 'lucide-react';
import type { GitHubUser, GitHubRepo } from '../../types/github.ts';
import { calculateProfileAudit, type SuggestionPriority } from '../../services/scoreService.ts';
import { Badge } from '../common/Badge.tsx';
import { Button } from '../common/Button.tsx';

interface ProfileAuditViewProps {
  user: GitHubUser | null;
  repos: GitHubRepo[];
  isDemoMode: boolean;
  onRefresh: () => void;
}

export function ProfileAuditView({ user, repos, isDemoMode }: ProfileAuditViewProps) {
  const [filterPriority, setFilterPriority] = useState<string>('all');
  const [completedIds, setCompletedIds] = useState<Set<string>>(new Set());
  const [copiedReport, setCopiedReport] = useState(false);

  const audit = useMemo(() => {
    return calculateProfileAudit(user, repos);
  }, [user, repos]);

  const toggleComplete = (id: string) => {
    setCompletedIds((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  };

  const filteredSuggestions = useMemo(() => {
    if (filterPriority === 'all') return audit.suggestions;
    return audit.suggestions.filter((s) => s.priority === filterPriority);
  }, [audit.suggestions, filterPriority]);

  const getPriorityBadge = (priority: SuggestionPriority) => {
    switch (priority) {
      case 'critical':
        return <Badge variant="rose" size="sm" dot>Critical Priority</Badge>;
      case 'high':
        return <Badge variant="amber" size="sm" dot>High Impact</Badge>;
      case 'medium':
        return <Badge variant="cyan" size="sm">Recommended</Badge>;
      case 'quick-win':
        return <Badge variant="emerald" size="sm">Quick Win</Badge>;
      default:
        return <Badge variant="muted" size="sm">{priority}</Badge>;
    }
  };

  const handleCopyReport = () => {
    const report = `# GitHub Profile & Repository Audit: @${user?.login || 'developer'}
**Overall Developer Score:** ${audit.overallScore}/100 (Grade: ${audit.grade})
**Engineering Archetype:** ${audit.archetype}

## Category Breakdown:
- Profile Presence: ${audit.categories.profile.score}/${audit.categories.profile.maxScore} (${audit.categories.profile.percentage}%)
- Repository Quality: ${audit.categories.repos.score}/${audit.categories.repos.maxScore} (${audit.categories.repos.percentage}%)
- Documentation & Licensing: ${audit.categories.documentation.score}/${audit.categories.documentation.maxScore} (${audit.categories.documentation.percentage}%)
- Discoverability & Topics: ${audit.categories.discoverability.score}/${audit.categories.discoverability.maxScore} (${audit.categories.discoverability.percentage}%)

## Repository Health:
- Repos with Descriptions: ${audit.stats.reposWithDescription}/${audit.stats.totalRepos}
- Repos with Open Source Licenses: ${audit.stats.reposWithLicense}/${audit.stats.totalRepos}
- Repos with Topics: ${audit.stats.reposWithTopics}/${audit.stats.totalRepos}
- Repos with Live Demos: ${audit.stats.reposWithHomepage}/${audit.stats.totalRepos}

## Priority Action Items (${audit.suggestions.length} suggestions):
${audit.suggestions.map((s, i) => `${i + 1}. [${s.priority.toUpperCase()}] ${s.title}: ${s.description}`).join('\n')}

*Generated by GitMetrics Intelligence Engine*
`;
    navigator.clipboard.writeText(report);
    setCopiedReport(true);
    setTimeout(() => setCopiedReport(false), 2500);
  };

  return (
    <div className="space-y-8">
      {/* Top Banner Card with Developer Score */}
      <div className="glass-panel p-6 sm:p-8 rounded-3xl border border-white/10 relative overflow-hidden bg-gradient-to-br from-[#0B0F19] to-[#060810]">
        <div className="flex flex-col lg:flex-row items-start lg:items-center justify-between gap-6">
          <div className="space-y-3">
            <div className="flex flex-wrap items-center gap-2">
              <Badge variant="cyan" size="sm">
                Algorithmic Audit
              </Badge>
              <Badge variant="violet" size="sm">
                {audit.archetype}
              </Badge>
              {isDemoMode && (
                <Badge variant="muted" size="sm">
                  Demo Profile
                </Badge>
              )}
            </div>

            <h2 className="text-3xl sm:text-4xl font-extrabold text-white tracking-tight">
              GitHub Profile &amp; Repository Scorecard
            </h2>
            <p className="text-xs sm:text-sm text-slate-400 max-w-2xl leading-relaxed">
              We analyze your public profile completeness, repository documentation quality, licensing compliance, and SEO discoverability to help you present your work at the highest standard.
            </p>
          </div>

          {/* Big Score Visual Badge */}
          <div className="flex items-center gap-4 bg-slate-900/90 p-4 sm:p-5 rounded-2xl border border-white/10 shrink-0">
            <div className="text-center">
              <div className="text-4xl sm:text-5xl font-mono font-extrabold text-transparent bg-clip-text bg-gradient-to-r from-cyan-400 via-blue-400 to-purple-400">
                {audit.overallScore}
                <span className="text-lg text-slate-400 font-normal">/100</span>
              </div>
              <div className="text-[11px] font-mono uppercase tracking-wider text-slate-400 mt-1">
                Developer Score
              </div>
            </div>

            <div className="w-px h-12 bg-white/10" />

            <div className="text-center px-2">
              <div
                className={`text-3xl sm:text-4xl font-mono font-black ${
                  audit.grade === 'A+' || audit.grade === 'A'
                    ? 'text-emerald-400'
                    : audit.grade === 'B'
                    ? 'text-cyan-400'
                    : 'text-amber-400'
                }`}
              >
                {audit.grade}
              </div>
              <div className="text-[11px] font-mono uppercase tracking-wider text-slate-400 mt-1">
                Rating
              </div>
            </div>
          </div>
        </div>

        {/* Category Progress Bars */}
        <div className="mt-8 pt-6 border-t border-white/5 grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
          {Object.values(audit.categories).map((cat) => (
            <div key={cat.name} className="p-3.5 rounded-xl bg-slate-900/40 border border-white/5 space-y-2">
              <div className="flex items-center justify-between text-xs font-mono">
                <span className="text-slate-300 font-semibold">{cat.name}</span>
                <span className="text-cyan-400 font-bold">
                  {cat.score}/{cat.maxScore}
                </span>
              </div>
              <div className="w-full bg-slate-800 h-1.5 rounded-full overflow-hidden">
                <div
                  className="bg-gradient-to-r from-cyan-500 to-blue-500 h-full rounded-full transition-all duration-700"
                  style={{ width: `${cat.percentage}%` }}
                />
              </div>
              <p className="text-[10px] text-slate-400 leading-snug">{cat.description}</p>
            </div>
          ))}
        </div>
      </div>

      {/* Repository Health Metrics Counter */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
        <div className="glass-panel p-4 rounded-2xl border border-white/10">
          <div className="flex items-center gap-2 text-xs font-mono text-slate-400 mb-1">
            <BookOpen className="w-3.5 h-3.5 text-cyan-400" />
            <span>Descriptions</span>
          </div>
          <div className="text-2xl font-bold font-mono text-white">
            {audit.stats.reposWithDescription}/{audit.stats.totalRepos}
          </div>
          <div className="text-[11px] text-slate-400 mt-0.5">
            {Math.round((audit.stats.reposWithDescription / Math.max(1, audit.stats.totalRepos)) * 100)}% coverage
          </div>
        </div>

        <div className="glass-panel p-4 rounded-2xl border border-white/10">
          <div className="flex items-center gap-2 text-xs font-mono text-slate-400 mb-1">
            <ShieldCheck className="w-3.5 h-3.5 text-emerald-400" />
            <span>Open Licenses</span>
          </div>
          <div className="text-2xl font-bold font-mono text-white">
            {audit.stats.reposWithLicense}/{audit.stats.totalRepos}
          </div>
          <div className="text-[11px] text-slate-400 mt-0.5">
            {Math.round((audit.stats.reposWithLicense / Math.max(1, audit.stats.totalRepos)) * 100)}% compliant
          </div>
        </div>

        <div className="glass-panel p-4 rounded-2xl border border-white/10">
          <div className="flex items-center gap-2 text-xs font-mono text-slate-400 mb-1">
            <Tag className="w-3.5 h-3.5 text-purple-400" />
            <span>Topic Tags</span>
          </div>
          <div className="text-2xl font-bold font-mono text-white">
            {audit.stats.reposWithTopics}/{audit.stats.totalRepos}
          </div>
          <div className="text-[11px] text-slate-400 mt-0.5">
            {Math.round((audit.stats.reposWithTopics / Math.max(1, audit.stats.totalRepos)) * 100)}% indexed
          </div>
        </div>

        <div className="glass-panel p-4 rounded-2xl border border-white/10">
          <div className="flex items-center gap-2 text-xs font-mono text-slate-400 mb-1">
            <Globe className="w-3.5 h-3.5 text-amber-400" />
            <span>Live Demos</span>
          </div>
          <div className="text-2xl font-bold font-mono text-white">
            {audit.stats.reposWithHomepage}/{audit.stats.totalRepos}
          </div>
          <div className="text-[11px] text-slate-400 mt-0.5">
            {Math.round((audit.stats.reposWithHomepage / Math.max(1, audit.stats.totalRepos)) * 100)}% deployed
          </div>
        </div>
      </div>

      {/* Actionable Suggestions & Improvement Checklist */}
      <div className="glass-panel p-6 sm:p-8 rounded-3xl border border-white/10 space-y-6">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
          <div>
            <h3 className="text-xl font-bold text-white flex items-center gap-2">
              <Lightbulb className="w-5 h-5 text-amber-400" />
              <span>Personalized Profile &amp; Repository Recommendations</span>
            </h3>
            <p className="text-xs text-slate-400 mt-1">
              Complete these recommendations to elevate your GitHub presence and portfolio discoverability.
            </p>
          </div>

          <Button
            size="sm"
            variant="secondary"
            onClick={handleCopyReport}
            leftIcon={copiedReport ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
          >
            {copiedReport ? 'Report Copied!' : 'Copy Audit Report'}
          </Button>
        </div>

        {/* Priority Filters */}
        <div className="flex flex-wrap items-center gap-2 text-xs font-mono">
          <button
            onClick={() => setFilterPriority('all')}
            className={`px-3 py-1.5 rounded-xl border transition-all ${
              filterPriority === 'all'
                ? 'bg-cyan-500/20 text-cyan-300 border-cyan-500/40'
                : 'bg-slate-900/40 text-slate-400 border-white/5 hover:text-white'
            }`}
          >
            All Suggestions ({audit.suggestions.length})
          </button>
          <button
            onClick={() => setFilterPriority('critical')}
            className={`px-3 py-1.5 rounded-xl border transition-all ${
              filterPriority === 'critical'
                ? 'bg-rose-500/20 text-rose-300 border-rose-500/40'
                : 'bg-slate-900/40 text-slate-400 border-white/5 hover:text-white'
            }`}
          >
            Critical
          </button>
          <button
            onClick={() => setFilterPriority('high')}
            className={`px-3 py-1.5 rounded-xl border transition-all ${
              filterPriority === 'high'
                ? 'bg-amber-500/20 text-amber-300 border-amber-500/40'
                : 'bg-slate-900/40 text-slate-400 border-white/5 hover:text-white'
            }`}
          >
            High Impact
          </button>
          <button
            onClick={() => setFilterPriority('quick-win')}
            className={`px-3 py-1.5 rounded-xl border transition-all ${
              filterPriority === 'quick-win'
                ? 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40'
                : 'bg-slate-900/40 text-slate-400 border-white/5 hover:text-white'
            }`}
          >
            Quick Wins
          </button>
        </div>

        {/* Suggestions Checklist Items */}
        <div className="space-y-4">
          {filteredSuggestions.map((sug) => {
            const isDone = completedIds.has(sug.id);
            return (
              <div
                key={sug.id}
                className={`p-5 rounded-2xl border transition-all ${
                  isDone
                    ? 'bg-emerald-500/5 border-emerald-500/20 opacity-70'
                    : 'bg-slate-900/50 border-white/5 hover:border-white/15'
                }`}
              >
                <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 mb-2">
                  <div className="flex items-center gap-3">
                    <button
                      onClick={() => toggleComplete(sug.id)}
                      className="text-slate-400 hover:text-emerald-400 transition-colors shrink-0"
                      title={isDone ? 'Mark as incomplete' : 'Mark as completed'}
                    >
                      <CheckCircle2
                        className={`w-5 h-5 ${
                          isDone ? 'text-emerald-400 fill-emerald-500/20' : 'text-slate-500'
                        }`}
                      />
                    </button>
                    <div>
                      <div className="flex items-center gap-2">
                        {getPriorityBadge(sug.priority)}
                        <h4
                          className={`font-bold text-sm sm:text-base ${
                            isDone ? 'line-through text-slate-400' : 'text-white'
                          }`}
                        >
                          {sug.title}
                        </h4>
                      </div>
                    </div>
                  </div>

                  {sug.targetUrl && (
                    <a
                      href={sug.targetUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-cyan-500/10 hover:bg-cyan-500/20 text-cyan-400 border border-cyan-500/30 text-xs font-mono font-semibold transition-all self-end sm:self-auto shrink-0"
                    >
                      <span>Fix on GitHub</span>
                      <ExternalLink className="w-3.5 h-3.5" />
                    </a>
                  )}
                </div>

                <div className="pl-8 space-y-2 mt-2">
                  <p className="text-xs text-slate-300 leading-relaxed">{sug.description}</p>
                  <div className="p-3 rounded-xl bg-black/40 border border-white/5 text-[11px] font-mono text-cyan-300 flex items-start gap-2">
                    <span className="text-cyan-400 font-bold shrink-0">Action Step:</span>
                    <span>{sug.actionGuide}</span>
                  </div>
                </div>
              </div>
            );
          })}

          {filteredSuggestions.length === 0 && (
            <div className="p-8 text-center text-xs font-mono text-slate-400">
              No recommendations match the selected filter.
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
